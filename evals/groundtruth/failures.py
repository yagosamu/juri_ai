"""Deterministic evidence for the questions production misses at recall@10. Shares its fixed
analysis protocol with significance.py; see that module's commit history for when the protocol
was set.

Production misses are taken from `results/production.json` where recall@10 == 0. For each, this
module shows the id, category and question, the golden passage's doc id, article header (from
`golden/candidates.jsonl`) and passage length, and for each of the five configs the rank of the
first hit or "miss". It writes the committed `results/failures.md`. No API call, no randomness.

Usage: .venv/Scripts/python.exe -m evals.groundtruth.failures
"""
import json
import sys

from evals.groundtruth.config import CANDIDATES, GOLDEN_SET, RESULTS_DIR
from evals.groundtruth.golden.schema import load_golden
from evals.groundtruth.scorers import Span, is_hit

CONFIG_ORDER = ("production", "chunk1500", "chunk800", "hybrid", "rerank")


def production_misses(production_result: dict) -> list[str]:
    """ids where recall@10 == 0 in results/production.json, in file order."""
    return [item["id"] for item in production_result["items"] if item["recall@10"] == 0.0]


def passage_info(golden_item: dict, candidates_by_id: dict) -> dict:
    """doc_id, article header (from golden/candidates.jsonl, "unknown" if the id is missing there)
    and the passage length in characters, for a golden item's single passage."""
    passage = golden_item["passages"][0]
    candidate = candidates_by_id.get(golden_item["id"])
    header = candidate["header"] if candidate else "unknown"
    return {"doc_id": passage["doc_id"], "header": header, "length": passage["end"] - passage["start"]}


def first_hit_rank(retrieved: list, passage: Span) -> int | None:
    """1-indexed rank of the first retrieved chunk that hits the passage (scorers.is_hit), or None
    when nothing in `retrieved` hits it."""
    for rank, chunk in enumerate(retrieved, start=1):
        doc_id, start, end = chunk
        if is_hit(Span(doc_id, start, end), passage):
            return rank
    return None


def build_failure_rows(miss_ids: list[str], golden_by_id: dict, candidates_by_id: dict,
                        results_by_config: dict, config_order=CONFIG_ORDER) -> list[dict]:
    """One row per production miss: id, category, question, the passage_info fields, and 'ranks',
    a dict of config name to first_hit_rank (an int or None) for every config in config_order."""
    rows = []
    for miss_id in miss_ids:
        golden_item = golden_by_id[miss_id]
        info = passage_info(golden_item, candidates_by_id)
        passage = golden_item["passages"][0]
        span = Span(passage["doc_id"], passage["start"], passage["end"])
        ranks = {}
        for config in config_order:
            item = next(i for i in results_by_config[config]["items"] if i["id"] == miss_id)
            ranks[config] = first_hit_rank(item["retrieved"], span)
        rows.append({
            "id": miss_id,
            "category": golden_item["category"],
            "question": golden_item["question"],
            "doc_id": info["doc_id"],
            "header": info["header"],
            "length": info["length"],
            "ranks": ranks,
        })
    return rows


def render_failures(rows: list[dict], config_order=CONFIG_ORDER) -> str:
    lines = [
        "# Production failures at recall@10",
        "",
        "Deterministic evidence for the questions `results/production.json` misses at recall@10. For "
        "each, the rank shown is the first retrieved chunk that hits the golden passage under the "
        "bidirectional hit rule in `scorers.py`, or \"miss\" when none of the top results hit it. "
        "This report shares its fixed analysis protocol with `results/significance.md`; both are "
        "generated by modules whose commit history records when that protocol was set.",
        "",
        f"Production misses at recall@10: {len(rows)}.",
        "",
    ]
    if not rows:
        lines.append("No production misses to report.")
        lines.append("")
        return "\n".join(lines)

    header = "| id | category | question | doc | article | passage length | " + \
        " | ".join(config_order) + " |"
    sep = "|" + "---|" * (6 + len(config_order))
    lines.append(header)
    lines.append(sep)
    for row in rows:
        rank_cells = []
        for config in config_order:
            rank = row["ranks"].get(config)
            rank_cells.append("miss" if rank is None else str(rank))
        lines.append(
            f"| {row['id']} | {row['category']} | {row['question']} | {row['doc_id']} | "
            f"{row['header']} | {row['length']} | " + " | ".join(rank_cells) + " |")
    lines.append("")
    return "\n".join(lines)


def _load_json(path):
    return json.loads(path.read_text(encoding="utf-8"))


def load_candidates(path=CANDIDATES) -> dict:
    """candidate_id -> candidate row, from golden/candidates.jsonl."""
    candidates_by_id = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line.strip():
            continue
        candidate = json.loads(line)
        candidates_by_id[candidate["candidate_id"]] = candidate
    return candidates_by_id


def build_failures_report(results_by_config: dict, golden: list, candidates_by_id: dict,
                           config_order=CONFIG_ORDER) -> str:
    """Pure: turns already-loaded results (name -> parsed results/<name>.json), golden items (as
    returned by golden.schema.load_golden) and candidates_by_id (as returned by load_candidates)
    into the exact text main() writes to results/failures.md. No file I/O, no randomness."""
    golden_by_id = {g.id: g.model_dump() for g in golden}
    miss_ids = production_misses(results_by_config["production"])
    rows = build_failure_rows(miss_ids, golden_by_id, candidates_by_id, results_by_config, config_order)
    return render_failures(rows, config_order)


def main() -> None:
    sys.stdout.reconfigure(encoding="utf-8")
    results_by_config = {name: _load_json(RESULTS_DIR / f"{name}.json") for name in CONFIG_ORDER}
    golden = load_golden(GOLDEN_SET)
    candidates_by_id = load_candidates()

    text = build_failures_report(results_by_config, golden, candidates_by_id)
    out_path = RESULTS_DIR / "failures.md"
    out_path.write_text(text, encoding="utf-8")
    print(out_path)


if __name__ == "__main__":
    main()
